CREATE TABLE customers (
    id bigint generated by default as identity primary key,
    identification_number text not null,
    identification_type text not null,
    verification_digit text,
    first_name text not null,
    middle_name text,
    first_surname text,
    second_surname text,
    display_name text,
    address text,
    phone text,
    email text,
    city_code text
);

CREATE TABLE equivalences (
    id bigint generated by default as identity primary key,
    category text not null,
    source_field text not null,
    target_field text not null,
    source_value text,
    target_value text
);

CREATE TABLE billing_documents (
    id bigint generated by default as identity primary key,
    document_type text not null,
    document_number text,
    external_number text,
    affected_document text,
    issue_date date not null,
    due_date date,
    payment_term_days integer,
    payment_method_code text,
    seller_identification text,
    warehouse_code text,
    description text,
    notes text,
    cost_center text,
    cost_subcenter text,
    billing_period text,
    period_start date,
    period_end date,
    agent_identification text,
    snapshot_identification_number text,
    snapshot_identification_type text,
    snapshot_verification_digit text,
    snapshot_first_name text,
    snapshot_middle_name text,
    snapshot_first_surname text,
    snapshot_second_surname text,
    snapshot_display_name text,
    snapshot_address text,
    snapshot_phone text,
    snapshot_email text,
    snapshot_city_code text,
    customer_id bigint not null references customers(id)
);

CREATE TABLE items (
    id bigint generated by default as identity primary key,
    item_reference text,
    service_code text,
    quantity numeric,
    price numeric,
    unit_amount numeric,
    line_amount numeric,
    vat_rate numeric,
    vat_amount numeric,
    consumption_tax_amount numeric,
    document_id bigint not null references billing_documents(id)
);

CREATE TABLE payments (
    id bigint generated by default as identity primary key,
    payment_method_code text,
    ledger_account text,
    amount numeric,
    due_date date,
    installment_number text,
    payer_identification text,
    document_id bigint not null references billing_documents(id)
);

CREATE TABLE adjustments (
    id bigint generated by default as identity primary key,
    adjustment_type text,
    concept_code text,
    description text,
    amount numeric,
    document_id bigint not null references billing_documents(id)
);

CREATE TABLE health_billing_data (
    id bigint generated by default as identity primary key,
    payment_modality text,
    benefit_plan_coverage text,
    contract_number text,
    policy_number text,
    copayment numeric,
    moderating_fee numeric,
    shared_payments numeric,
    advances numeric,
    document_id bigint not null references billing_documents(id)
);

CREATE TABLE integration_requests (
    id bigint generated by default as identity primary key,
    source_system text,
    source_document_number text,
    original_payload text not null,
    received_at timestamptz not null,
    status text not null,
    document_id bigint unique references billing_documents(id)
);

CREATE TABLE processing_events (
    id bigint generated by default as identity primary key,
    occurred_at timestamptz not null,
    actor text,
    operation text not null,
    outcome text not null,
    request_id bigint not null references integration_requests(id)
);

CREATE TABLE event_messages(event_id bigint not null references processing_events(id), position integer not null, message text not null, primary key(event_id,position));

CREATE UNIQUE INDEX uq_customer_id_number ON customers(identification_number);

CREATE UNIQUE INDEX uq_equivalence ON equivalences(category,source_field,target_field,coalesce(source_value,''));

CREATE INDEX ix_processing_request ON processing_events(request_id,id);

CREATE INDEX ix_doc_date ON billing_documents(issue_date,id);

CREATE INDEX ix_items_document ON items(document_id);

CREATE INDEX ix_payments_document ON payments(document_id);

CREATE INDEX ix_adjustments_document ON adjustments(document_id);

CREATE INDEX ix_health_billing_data_document ON health_billing_data(document_id);
-- Ejecutar después de crear billing_documents y antes de habilitar escrituras.
ALTER TABLE billing_documents
    
    ADD CONSTRAINT ck_billing_document_identity CHECK (
        btrim(document_type) <> ''
        AND (nullif(btrim(document_number), '') IS NOT NULL
             OR nullif(btrim(external_number), '') IS NOT NULL)
    );

CREATE UNIQUE INDEX uq_billing_document_number
    ON billing_documents (btrim(document_type), btrim(document_number))
    WHERE nullif(btrim(document_number), '') IS NOT NULL;

CREATE UNIQUE INDEX uq_billing_external_number
    ON billing_documents (btrim(document_type), btrim(external_number))
    WHERE nullif(btrim(document_number), '') IS NULL;
